CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    full_price DECIMAL(19,2) NOT NULL,
    down_payment DECIMAL(19,2) NOT NULL,
    daily_amount DECIMAL(19,2) NOT NULL,
    payment_plan_name VARCHAR(255),
    payment_mode VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone_number VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    customer_code VARCHAR(255) NOT NULL UNIQUE,
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS cash_loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    amount_requested DECIMAL(19,2) NOT NULL,
    approved_amount DECIMAL(19,2) NOT NULL,
    balance_remaining DECIMAL(19,2) NOT NULL,
    monthly_rate DECIMAL(19,2) NOT NULL,
    purpose VARCHAR(255),
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_cash_loan_customer
        FOREIGN KEY (customer_id) REFERENCES user_accounts(id)
);

CREATE TABLE IF NOT EXISTS payment_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_name VARCHAR(255) NOT NULL,
    duration_days INTEGER NOT NULL,
    deposit_amount DECIMAL(19,2) NOT NULL,
    daily_amount DECIMAL(19,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS payment_modes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode_name VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS merchants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_code VARCHAR(255) NOT NULL UNIQUE,
    business_name VARCHAR(255) NOT NULL,
    registration_number VARCHAR(255),
    phone VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    address VARCHAR(255),
    status VARCHAR(50) NOT NULL,
    owner_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_merchant_owner
        FOREIGN KEY (owner_id) REFERENCES user_accounts(id)
);

CREATE TABLE IF NOT EXISTS agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_code VARCHAR(255) NOT NULL UNIQUE,
    user_account_id BIGINT NOT NULL UNIQUE,
    merchant_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_agent_user
        FOREIGN KEY (user_account_id) REFERENCES user_accounts(id),
    CONSTRAINT fk_agent_merchant
        FOREIGN KEY (merchant_id) REFERENCES merchants(id)
);

CREATE TABLE IF NOT EXISTS devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code VARCHAR(255) NOT NULL UNIQUE,
    imei VARCHAR(255) UNIQUE,
    serial_number VARCHAR(255) UNIQUE,
    product_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    merchant_id BIGINT,
    agent_id BIGINT,
    customer_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_device_product
        FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_device_merchant
        FOREIGN KEY (merchant_id) REFERENCES merchants(id),
    CONSTRAINT fk_device_agent
        FOREIGN KEY (agent_id) REFERENCES agents(id),
    CONSTRAINT fk_device_customer
        FOREIGN KEY (customer_id) REFERENCES user_accounts(id)
);

CREATE TABLE IF NOT EXISTS financing_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_number VARCHAR(255) UNIQUE,
    customer_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    payment_plan_id BIGINT NOT NULL,
    payment_mode_id BIGINT,
    device_price DECIMAL(19,2) NOT NULL,
    deposit_amount DECIMAL(19,2) NOT NULL,
    requested_principal DECIMAL(19,2) NOT NULL,
    installment_amount DECIMAL(19,2),
    approved_principal DECIMAL(19,2),
    reviewed_by_id BIGINT,
    decision_reason VARCHAR(500),
    submitted_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_financing_app_customer
        FOREIGN KEY (customer_id) REFERENCES user_accounts(id),
    CONSTRAINT fk_financing_app_device
        FOREIGN KEY (device_id) REFERENCES devices(id),
    CONSTRAINT fk_financing_app_plan
        FOREIGN KEY (payment_plan_id) REFERENCES payment_plans(id),
    CONSTRAINT fk_financing_app_mode
        FOREIGN KEY (payment_mode_id) REFERENCES payment_modes(id),
    CONSTRAINT fk_financing_app_reviewer
        FOREIGN KEY (reviewed_by_id) REFERENCES user_accounts(id)
);

CREATE TABLE IF NOT EXISTS loan_contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    device_id BIGINT,
    application_id BIGINT,
    contract_number VARCHAR(255) UNIQUE,
    deposit_paid DECIMAL(19,2) NOT NULL,
    amount_remaining DECIMAL(19,2) NOT NULL,
    amount_paid DECIMAL(19,2) NOT NULL,
    installment_paid DECIMAL(19,2) NOT NULL,
    daily_amount DECIMAL(19,2) NOT NULL,
    principal_amount DECIMAL(19,2),
    total_payable DECIMAL(19,2),
    payment_frequency VARCHAR(20),
    device_price DECIMAL(19,2),
    plan_name VARCHAR(255),
    plan_duration_days INTEGER,
    loan_status VARCHAR(50) NOT NULL,
    next_payment_due_date DATE,
    schedule_anchor_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_loan_contract_product
        FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_loan_contract_customer
        FOREIGN KEY (customer_id) REFERENCES user_accounts(id),
    CONSTRAINT fk_loan_contract_device
        FOREIGN KEY (device_id) REFERENCES devices(id),
    CONSTRAINT fk_loan_contract_application
        FOREIGN KEY (application_id) REFERENCES financing_applications(id)
);

CREATE TABLE IF NOT EXISTS payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(255) UNIQUE,
    contract_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    provider_reference VARCHAR(255) UNIQUE,
    idempotency_key VARCHAR(255) UNIQUE,
    failure_reason VARCHAR(500),
    posted_amount DECIMAL(19,2),
    reversal_reference VARCHAR(255) UNIQUE,
    reversal_reason VARCHAR(500),
    requested_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    posted_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_payment_tx_contract
        FOREIGN KEY (contract_id) REFERENCES loan_contracts(id),
    CONSTRAINT fk_payment_tx_customer
        FOREIGN KEY (customer_id) REFERENCES user_accounts(id)
);

CREATE TABLE IF NOT EXISTS provider_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(20) NOT NULL,
    provider_reference VARCHAR(255) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    transaction_time TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    raw_metadata VARCHAR(500),
    imported_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_provider_tx_ref ON provider_transactions(provider_reference);
CREATE INDEX IF NOT EXISTS idx_provider_tx_provider ON provider_transactions(provider);
CREATE INDEX IF NOT EXISTS idx_provider_tx_time ON provider_transactions(transaction_time);

CREATE TABLE IF NOT EXISTS reconciliation_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_number VARCHAR(255) UNIQUE,
    provider VARCHAR(20),
    window_start TIMESTAMP,
    window_end TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    total_records BIGINT NOT NULL,
    matched_count BIGINT NOT NULL,
    exception_count BIGINT NOT NULL,
    started_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS reconciliation_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_transaction_id BIGINT,
    provider_transaction_id BIGINT,
    batch_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    difference_amount DECIMAL(19,2),
    reason VARCHAR(500),
    reconciled_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_recon_record_tx
        FOREIGN KEY (payment_transaction_id) REFERENCES payment_transactions(id),
    CONSTRAINT fk_recon_record_provider_tx
        FOREIGN KEY (provider_transaction_id) REFERENCES provider_transactions(id),
    CONSTRAINT fk_recon_record_batch
        FOREIGN KEY (batch_id) REFERENCES reconciliation_batches(id)
);

CREATE INDEX IF NOT EXISTS idx_recon_records_batch ON reconciliation_records(batch_id);
CREATE INDEX IF NOT EXISTS idx_recon_records_status ON reconciliation_records(status);
CREATE INDEX IF NOT EXISTS idx_recon_records_tx ON reconciliation_records(payment_transaction_id);
CREATE INDEX IF NOT EXISTS idx_recon_records_provider_tx ON reconciliation_records(provider_transaction_id);

CREATE TABLE IF NOT EXISTS payment_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR(255) UNIQUE,
    transaction_id BIGINT NOT NULL UNIQUE,
    amount_applied DECIMAL(19,2) NOT NULL,
    balance_after DECIMAL(19,2) NOT NULL,
    posted_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_receipt_transaction
        FOREIGN KEY (transaction_id) REFERENCES payment_transactions(id)
);

CREATE TABLE IF NOT EXISTS payment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_transaction_id BIGINT NOT NULL,
    contract_id BIGINT NOT NULL,
    allocation_date DATE NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    sequence INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    reversed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_allocation_tx
        FOREIGN KEY (payment_transaction_id) REFERENCES payment_transactions(id),
    CONSTRAINT fk_allocation_contract
        FOREIGN KEY (contract_id) REFERENCES loan_contracts(id),
    CONSTRAINT uq_allocation_tx_sequence
        UNIQUE (payment_transaction_id, sequence)
);

CREATE INDEX IF NOT EXISTS idx_allocations_contract ON payment_allocations(contract_id);

CREATE TABLE IF NOT EXISTS device_lock_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL UNIQUE,
    device_id BIGINT NOT NULL,
    secret_key VARCHAR(64) NOT NULL,
    anchor_date DATE NOT NULL,
    last_sequence INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_lock_key_contract
        FOREIGN KEY (contract_id) REFERENCES loan_contracts(id),
    CONSTRAINT fk_lock_key_device
        FOREIGN KEY (device_id) REFERENCES devices(id)
);

CREATE TABLE IF NOT EXISTS unlock_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lock_key_id BIGINT NOT NULL,
    sequence INTEGER NOT NULL,
    valid_until DATE,
    permanent BOOLEAN NOT NULL,
    code VARCHAR(12) NOT NULL,
    reason VARCHAR(20) NOT NULL,
    payment_transaction_id BIGINT,
    issued_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_unlock_code_key
        FOREIGN KEY (lock_key_id) REFERENCES device_lock_keys(id),
    CONSTRAINT fk_unlock_code_tx
        FOREIGN KEY (payment_transaction_id) REFERENCES payment_transactions(id),
    CONSTRAINT uq_unlock_code_sequence
        UNIQUE (lock_key_id, sequence)
);

CREATE INDEX IF NOT EXISTS idx_lock_keys_device ON device_lock_keys(device_id);

